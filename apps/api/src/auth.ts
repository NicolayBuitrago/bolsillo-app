import { drizzleAdapter } from '@better-auth/drizzle-adapter';
import { expo } from '@better-auth/expo';
import { type Database, ensureUserDefaults } from '@bolsillo/db';
import * as schema from '@bolsillo/db/schema';
import { betterAuth } from 'better-auth';
import type { Env } from './env';
import type { Logger } from './logger';

export const AUTH_BASE_PATH = '/api/auth';

/** Deep-link scheme of the mobile app (apps/mobile/app.config.ts). */
const MOBILE_ORIGIN = 'bolsillo://';

export interface AuthDeps {
  db: Database;
  env: Pick<Env, 'NODE_ENV' | 'BETTER_AUTH_SECRET' | 'BETTER_AUTH_URL' | 'WEB_ORIGIN'>;
  logger: Logger;
}

/**
 * Better Auth with email + password. Sessions live in Postgres; ids are native
 * uuids generated by the database.
 *
 * Better Auth runs `after` hooks once the user row is committed, so the
 * defaults (settings + categories) are created in their own transaction and
 * re-checked on every new session: a failed bootstrap repairs itself on the
 * next sign-in.
 */
export function createAuth({ db, env, logger }: AuthDeps) {
  const bootstrap = async (userId: string) => {
    try {
      await ensureUserDefaults(db, userId);
    } catch (error) {
      logger.error({ userId, err: { name: (error as Error).name } }, 'user bootstrap failed');
    }
  };

  return betterAuth({
    appName: 'Bolsillo',
    basePath: AUTH_BASE_PATH,
    baseURL: env.BETTER_AUTH_URL,
    secret: env.BETTER_AUTH_SECRET,
    database: drizzleAdapter(db, { provider: 'pg', schema }),
    emailAndPassword: { enabled: true, minPasswordLength: 8, maxPasswordLength: 128 },
    trustedOrigins: [
      env.WEB_ORIGIN,
      MOBILE_ORIGIN,
      // Expo dev client URLs; never trusted in production.
      ...(env.NODE_ENV === 'development' ? ['exp://'] : []),
    ],
    plugins: [expo()],
    advanced: {
      database: { generateId: 'uuid' },
      // Better Auth skips the origin check under NODE_ENV=test; keep it on so
      // tests exercise the same CSRF protection as production.
      disableOriginCheck: false,
    },
    // docs/05-api.md: 10 requests per minute per IP. Sign-in and sign-up keep
    // Better Auth's stricter built-in rule; session reads are not limited.
    rateLimit: {
      enabled: env.NODE_ENV !== 'test',
      window: 60,
      max: 10,
      storage: 'memory',
      customRules: { '/get-session': false },
    },
    databaseHooks: {
      user: { create: { after: (user) => bootstrap(user.id) } },
      session: { create: { after: (session) => bootstrap(session.userId) } },
    },
    telemetry: { enabled: false },
  });
}

export type Auth = ReturnType<typeof createAuth>;
