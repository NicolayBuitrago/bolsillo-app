// Generates tokens/tokens.css (consumed by apps/web) from tokens/tokens.json.
// `--check` fails if the committed CSS is out of date.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = join(dirname(fileURLToPath(import.meta.url)), '..', 'tokens');
const tokens = JSON.parse(readFileSync(join(dir, 'tokens.json'), 'utf8'));

const block = (selector, scheme) => {
  const lines = Object.entries(tokens.color[scheme]).map(([k, v]) => `  --${k}: ${v};`);
  if (scheme === 'light') {
    lines.push(`  --radius: ${tokens.radius.md}px;`);
  }
  return `${selector} {\n${lines.join('\n')}\n}\n`;
};

const indent = (text) => text.replace(/^(?=.)/gm, '  ');

// Dark follows the system unless the page opts into `.light`; `.dark` forces it.
const css = `/* Generated by scripts/build-tokens-css.mjs from tokens.json. Do not edit. */
${block(':root', 'light')}
@media (prefers-color-scheme: dark) {
${indent(block(':root:not(.light)', 'dark'))}}

${block('.dark', 'dark')}`;

const target = join(dir, 'tokens.css');
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== css) {
    console.error('tokens.css is out of date. Run: pnpm --filter @bolsillo/config tokens:css');
    process.exit(1);
  }
} else {
  writeFileSync(target, css);
}
